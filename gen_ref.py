#!/usr/bin/env python3
"""
Break lispBM documentation into section-wise reference files for the vesc-lispbm skill.

Usage:
    python3 gen_ref.py [--lispbm-root /path/to/lispBM] [--out /path/to/output]

Generates:
    ref/*.md        - Section files extracted from README.md and CLAUDE.md
    ref/doc/*.md    - Filtered doc files important for writing lispbm scripts
    ref/INDEX.md    - Master index of all generated sections

Defaults:
    --lispbm-root  ../lispBM relative to this script, the bldc checkout layout
    --out          ref/ next to this script
"""

import re
import shutil
import argparse
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
DEFAULT_LISPBM_ROOT = SCRIPT_DIR.parent / "lispBM"
DEFAULT_OUT = SCRIPT_DIR / "ref"

# Doc files relevant for *writing lispbm scripts* (not C internals, fonts, etc.)
RELEVANT_DOCS = [
    "lbmref.md",       # Full language reference - essential
    "gotchas.md",      # Gotchas and caveats - important
    "runtimeref.md",   # Runtime extensions - important for VESC
    "displayref.md",   # Display library - VESC-specific
    "dynref.md",       # Dynamic loadable functions - useful
]


def slugify(text: str) -> str:
    """Convert a header text to a filename-safe slug."""
    text = text.strip().lower()
    text = re.sub(r'[^\w\s-]', '', text)
    text = re.sub(r'[\s_]+', '-', text)
    text = re.sub(r'-+', '-', text)
    return text.strip('-')


def split_markdown_by_sections(content: str, base_level: int = 2) -> list[dict]:
    """
    Split markdown content into sections by headers at the given base level.
    Returns list of {title, level, slug, content} dicts.
    """
    lines = content.split('\n')
    sections = []
    current_title = "preamble"
    current_lines = []
    current_level = 0

    header_re = re.compile(r'^(#{1,6})\s+(.+)$')

    for line in lines:
        m = header_re.match(line)
        if m:
            level = len(m.group(1))
            title = m.group(2).strip()

            # When we hit a header at or above base level, start a new section
            if level <= base_level:
                # Save previous section
                if current_lines:
                    sections.append({
                        'title': current_title,
                        'level': current_level,
                        'slug': slugify(current_title) if current_title != "preamble" else "preamble",
                        'content': '\n'.join(current_lines).strip(),
                    })
                current_title = title
                current_level = level
                current_lines = [line]
            else:
                current_lines.append(line)
        else:
            current_lines.append(line)

    # Save last section
    if current_lines:
        sections.append({
            'title': current_title,
            'level': current_level,
            'slug': slugify(current_title) if current_title != "preamble" else "preamble",
            'content': '\n'.join(current_lines).strip(),
        })

    return sections


def write_section_files(sections: list[dict], out_dir: Path) -> list[dict]:
    """Write each section to a file. Returns metadata for index."""
    meta = []
    for i, sec in enumerate(sections):
        if not sec['content'].strip():
            continue
        fname = f"{i:02d}-{sec['slug']}.md"
        fpath = out_dir / fname
        fpath.write_text(sec['content'], encoding='utf-8')
        meta.append({
            'title': sec['title'],
            'file': fname,
            'level': sec['level'],
        })
    return meta


def generate_index(meta: list[dict], doc_files: list[str]) -> str:
    """Generate the master INDEX.md."""
    lines = [
        "# VESC LispBM Skill Reference Index",
        "",
        "Auto-generated by `gen_ref.py`. Do not edit manually.",
        "",
        "## Language Reference Sections (from lbmref.md)",
        "",
    ]
    for m in meta:
        indent = "  " * (m['level'] - 2) if m['level'] > 2 else ""
        lines.append(f"{indent}- [{m['title']}]({m['file']})")

    lines.extend([
        "",
        "## Filtered Doc Files (for writing lispbm scripts)",
        "",
    ])
    for df in doc_files:
        lines.append(f"- [doc/{df}](doc/{df})")

    lines.append("")
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description="Generate lispBM reference sections")
    parser.add_argument("--lispbm-root", default=DEFAULT_LISPBM_ROOT,
                        help="Path to lispBM repo root")
    parser.add_argument("--out", default=DEFAULT_OUT,
                        help="Output directory for ref files")
    args = parser.parse_args()

    lispbm_root = Path(args.lispbm_root)
    out_dir = Path(args.out)
    doc_out = out_dir / "doc"

    out_dir.mkdir(parents=True, exist_ok=True)
    doc_out.mkdir(parents=True, exist_ok=True)

    # --- 1. Split lbmref.md into sections ---
    lbmref_path = lispbm_root / "doc" / "lbmref.md"
    if not lbmref_path.exists():
        print(f"ERROR: {lbmref_path} not found")
        return 1

    content = lbmref_path.read_text(encoding='utf-8')
    sections = split_markdown_by_sections(content, base_level=2)
    print(f"Split lbmref.md into {len(sections)} sections")
    meta = write_section_files(sections, out_dir)

    # --- 2. Copy relevant doc files ---
    doc_src = lispbm_root / "doc"
    copied_docs = []
    for doc_name in RELEVANT_DOCS:
        src = doc_src / doc_name
        if src.exists():
            shutil.copy2(src, doc_out / doc_name)
            copied_docs.append(doc_name)
            print(f"  Copied doc/{doc_name}")
        else:
            print(f"  WARN: {src} not found, skipping")

    # --- 3. Generate index ---
    index = generate_index(meta, copied_docs)
    (out_dir / "INDEX.md").write_text(index, encoding='utf-8')
    print(f"\nGenerated index: {out_dir / 'INDEX.md'}")
    print(f"Total: {len(meta)} sections, {len(copied_docs)} doc files")

    return 0


if __name__ == "__main__":
    exit(main())
