# --------------------------------------------------------------------------- #
# QML component scanning
# --------------------------------------------------------------------------- #

ROOT_RE = re.compile(r"^([A-Z][A-Za-z0-9_]*)\s*\{", re.M)
PROP_RE = re.compile(r"^\s*(?:readonly\s+)?property\s+([A-Za-z_][\w.]*)\s+([A-Za-z_]\w*)")
SIGNAL_RE = re.compile(r"^\s*signal\s+([A-Za-z_]\w*)\s*\(")
FUNC_RE = re.compile(r"^\s*function\s+([A-Za-z_]\w*)\s*\(")
IMPORT_RE = re.compile(r"^\s*import\s+(.+)$")


def scan_qml(path: Path) -> dict:
    """Root type, root-level properties/signals/functions and imports of a QML file."""
    text = path.read_text(encoding="utf-8", errors="replace")
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)

    imports = []
    root_type = "?"
    depth = 0
    props, signals, funcs = [], [], []

    for raw in text.splitlines():
        line = raw.split("//", 1)[0]
        if depth == 0:
            im = IMPORT_RE.match(raw)
            if im:
                imports.append(im.group(1).strip())
                continue
            rm = ROOT_RE.match(raw)
            if rm and root_type == "?":
                root_type = rm.group(1)
        pm = PROP_RE.match(line)
        if pm and depth == 1:
            props.append(f"`{pm.group(2)}` ({pm.group(1)})")
        sm = SIGNAL_RE.match(line)
        if sm and depth == 1:
            signals.append(f"`{sm.group(1)}()`")
        fm = FUNC_RE.match(line)
        if fm and depth == 1:
            funcs.append(f"`{fm.group(1)}()`")
        depth += line.count("{") - line.count("}")
        depth = max(depth, 0)

    return {
        "root": root_type,
        "props": props,
        "signals": signals,
        "funcs": funcs,
        "imports": imports,
    }


def qrc_entries(qrc: Path) -> tuple[str, list[Path]]:
    tree = ET.parse(qrc)
    root = tree.getroot()
    files: list[Path] = []
    for res in root.findall("qresource"):
        prefix = res.get("prefix", "/")
        for f in res.findall("file"):
            content = (f.text or "").strip()
            if content.endswith(".qml"):
                files.append(Path(prefix.strip("/")) / content)
    return qrc.name, files


