def render_type(info: TypeInfo, heading: str, intro: str, anchor: str, level: int = 2) -> list[str]:
    hashes = "#" * level
    out = [f"{hashes} {heading}", ""]
    if intro:
        out += [intro, ""]
    if info.doc:
        out += [info.doc, ""]
    out.append(f"Source: `{anchor}:{info.line}`")
    out.append("")

    groups: list[tuple[str, list[Entry]]] = [
        ("Methods (call these from QML)", [e for e in info.entries if e.kind == "method"]),
        ("Signals (connect with `Connections`)", [e for e in info.entries if e.kind == "signal"]),
        ("Properties", [e for e in info.entries if e.kind == "property"]),
    ]
    for title, entries in groups:
        if not entries:
            continue
        out += [f"{'#' * (level + 1)} {title}", ""]
        plain = [e for e in entries if not e.guard]
        guarded = [e for e in entries if e.guard]
        if plain:
            out += _table(plain, anchor, kind=entries[0].kind)
            out.append("")
        for g in dict.fromkeys(e.guard for e in guarded):
            sel = [e for e in guarded if e.guard == g]
            label = _guard_label(g)
            out += [f"*{label}*", "", *_table(sel, anchor, kind=entries[0].kind), ""]
    return out


def _guard_label(guard: str) -> str:
    bits = []
    for part in guard.split(" & "):
        part = part.strip()
        if part.startswith("not "):
            bits.append(f"`{part[4:]}` is not defined")
        else:
            bits.append(f"`{part}` is defined")
    return "Only when " + " and ".join(bits)


def _table(entries: list[Entry], anchor: str, kind: str) -> list[str]:
    if kind == "property":
        rows = ["| Property | Type | Source |", "|---|---|---|"]
        for e in entries:
            doc = f" — {e.doc}" if e.doc else ""
            rows.append(f"| `{e.signature}` | `{e.ptype}` | `{anchor}:{e.line}`{doc} |")
        return rows
    rows = ["| Signature | Source |", "|---|---|"]
    for e in entries:
        doc = f" — {escape_pipes(e.doc)}" if e.doc else ""
        rows.append(f"| `{escape_pipes(e.signature)}` | `{anchor}:{e.line}`{doc} |")
    return rows


def escape_pipes(text: str) -> str:
    return text.replace("|", "\\|")


def provenance(root: Path) -> str:
    try:
        rev = subprocess.run(["git", "-C", str(root), "rev-parse", "--short", "HEAD"],
                             capture_output=True, text=True, check=True).stdout.strip()
        dirty = subprocess.run(["git", "-C", str(root), "status", "--porcelain"],
                               capture_output=True, text=True, check=True).stdout.strip()
        return f"vesc_tool `{rev}`" + (" (working tree dirty)" if dirty else "")
    except (subprocess.CalledProcessError, FileNotFoundError):
        return "vesc_tool (unknown revision)"


