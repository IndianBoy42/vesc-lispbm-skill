#!/usr/bin/env python3
"""
Generate the device-QML reference for VESC Tool.

A custom VESC GUI is QML that VESC Tool reads off the controller and instantiates
in its own Qt engine. The objects it can reach are therefore whatever VESC Tool
exposes to QML, which changes with every VESC Tool release. This script derives
that surface from a vesc_tool checkout instead of restating it by hand:

  * the C++ objects injected into the QML context (`VescIf`, `Utility`),
  * the types a package instantiates through its own imports
    (`Commands`, `ConfigParams`, ...),
  * the Q_GADGET structs those return (`FW_RX_PARAMS`, `MC_VALUES`, ...),
  * every QML component reachable through the bundled qrc files
    (`import "qrc:/mobile"`, `import "qrc:/res/qml"`).

Only members QML can actually call are emitted: `Q_INVOKABLE`, `public slots`
(slots are invokable from QML), `Q_PROPERTY` and signals. Plain C++ methods and
private sections are dropped, because a package cannot see them.

Usage:
    python3 gen_qml_refs.py [--vesc-tool-root PATH] [--out DIR]

Defaults:
    --vesc-tool-root  ~/dev/vesc_tool
    --out             <this script's directory>/ref

Outputs (all overwritten):
    ref/api-vescinterface.md   VescIf: methods, signals
    ref/api-utility.md         Utility: static helpers, theme and colour lookups
    ref/api-commands.md        Commands: packet senders, values, custom app data
    ref/api-configparams.md    ConfigParams: parameter get/set by name
    ref/api-datatypes.md       Q_GADGET structs and their QML properties
    ref/components.md          QML components shipped in vesc_tool's qrc files
    ref/INDEX.md               counts, provenance, what is not covered

Deliberately not generated: the IO-board, BMS and firmware-upload objects
(`BleUart`, `Esp32Flash`, `FwHelper`, `TcpHub`, `LogReader`/`LogWriter`,
`CodeLoader`, `VminiMp3`, `Vesc3dItem`, `SysCmd`). They are registered for QML
(main.cpp:251-268) but they are VESC Tool application objects, not part of the
GUI contract a package should depend on; add them here if that changes.
"""

