def build_api_docs(root: Path, out_dir: Path) -> dict[str, int]:
    counts: dict[str, int] = {}
    prov = provenance(root)

    for spec in TYPE_DOCS:
        path = root / spec["file"]
        info = parse_type(path, spec["type"], spec["kind"])
        if info is None:
            print(f"warning: {spec['type']} not found in {path}", file=sys.stderr)
            continue
        anchor = f"vesc_tool/{spec['file']}"
        lines = doc_header(spec["title"], spec["blurb"], prov)
        lines += render_type(info, spec["type"], "", anchor)
        (out_dir / spec["out"]).write_text("\n".join(lines).rstrip() + "\n")
        counts[spec["out"]] = len(info.entries)

    # Q_GADGET structs: the values the API hands back into QML.
    gadgets: list[TypeInfo] = []
    data_lines = read_lines(root / "datatypes.h")
    for i, line in enumerate(data_lines):
        m = CLASS_RE.match(line)
        if not m or m.group(1) != "struct":
            continue
        end = block_range(data_lines, i)
        body = "\n".join(data_lines[i + 1:end])
        if "Q_GADGET" not in body and "Q_OBJECT" not in body:
            continue
        info = parse_type(root / "datatypes.h", m.group(2), "gadget")
        if info and info.entries:
            gadgets.append(info)

    lines = doc_header(
        "Value types (Q_GADGET)",
        "These are the objects the API hands back: `VescIf.getLastFwRxParams()` returns "
        "`FW_RX_PARAMS`, `Commands.valuesReceived` carries `MC_VALUES`, and so on. Their "
        "`Q_PROPERTY` members are readable in QML as normal properties. Enum-typed members "
        "(`mc_fault_code`, `HW_TYPE`) compare against the enum keys listed in `datatypes.h`.",
        prov,
    )
    for info in gadgets:
        lines += render_type(info, info.name, "", "vesc_tool/datatypes.h")
    (out_dir / "api-datatypes.md").write_text("\n".join(lines).rstrip() + "\n")
    counts["api-datatypes.md"] = len(gadgets)

    return counts


