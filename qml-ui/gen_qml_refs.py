# --------------------------------------------------------------------------- #
# C++ header scanning
# --------------------------------------------------------------------------- #

@dataclass
class Entry:
    """One QML-reachable member of a C++ type."""
    signature: str
    line: int
    kind: str            # "method" | "signal" | "property"
    guard: str = ""      # preprocessor condition that wraps it, "" if unconditional
    doc: str = ""
    ret: str = ""
    ptype: str = ""


@dataclass
class TypeInfo:
    name: str
    path: Path
    line: int
    doc: str = ""
    entries: list[Entry] = field(default_factory=list)


SECTION_RE = re.compile(r"^\s*(?:(public|private|protected)\s+)?(slots|signals|qml_methods)\s*:\s*$")
VISIBILITY_RE = re.compile(r"^\s*(public|private|protected)\s*:\s*$")
CLASS_RE = re.compile(r"^\s*(class|struct)\s+([A-Za-z_]\w*)\b([^;{]*)\{\s*$")
IFDEF_RE = re.compile(r"^\s*#\s*(if|ifdef|ifndef|elif|else|endif)\b(.*)$")


def read_lines(path: Path) -> list[str]:
    return path.read_text(encoding="utf-8", errors="replace").splitlines()


def block_range(lines: list[str], start: int) -> int:
    """Return the index of the line holding the closing brace of the block opened on `start`."""
    depth = 0
    for i in range(start, len(lines)):
        code = _strip_line_comment(lines[i])
        depth += code.count("{") - code.count("}")
        if depth <= 0:
            return i
    return len(lines) - 1


def _strip_line_comment(line: str) -> str:
    idx = line.find("//")
    return line if idx < 0 else line[:idx]


def _strip_block_comments(text: str) -> str:
    return re.sub(r"/\*.*?\*/", "", text, flags=re.S)


def _clean_signature(text: str) -> str:
    text = _strip_block_comments(text)
    text = re.sub(r"\s+", " ", text).strip()
    return text


def _split_top_level(text: str, sep: str = ",") -> list[str]:
    out, depth, cur = [], 0, ""
    for ch in text:
        if ch in "(<[":
            depth += 1
        elif ch in ")>]":
            depth -= 1
        if ch == sep and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur)
    return out


def _format_args(args: str) -> str:
    args = re.sub(r"\s+", " ", args).strip()
    if not args:
        return ""
    return ", ".join(a.strip() for a in _split_top_level(args))


def _parse_method(stmt: str) -> tuple[str, str] | None:
    """Return (return type, signature) for a Q_INVOKABLE or slot declaration."""
    stmt = _strip_block_comments(stmt)
    stmt = stmt.split("{", 1)[0]           # drop an inline body
    stmt = stmt.rstrip(";").strip()
    stmt = re.sub(r"^Q_INVOKABLE\s+", "", stmt)
    stmt = re.sub(r"^(static|virtual|inline)\s+", "", stmt)
    m = re.match(r"^(?P<ret>.+?)\s+(?P<name>[A-Za-z_]\w*)\s*\((?P<args>.*)\)\s*(?:const)?$", stmt, re.S)
    if not m:
        return None
    name = m.group("name")
    # A declaration without a return type would be a bare constructor; those are
    # not callable from QML, so drop them.
    if not m.group("ret").strip():
        return None
    return m.group("ret").strip(), f"{name}({_format_args(m.group('args'))})"


def _parse_property(stmt: str) -> tuple[str, str, str] | None:
    """Return (type, name, full declaration) for a Q_PROPERTY."""
    m = re.match(r"Q_PROPERTY\s*\((.*)\)\s*;?$", stmt, re.S)
    if not m:
        return None
    parts = _split_top_level(m.group(1), " ")
    words = [w for w in re.split(r"\s+", m.group(1).strip()) if w]
    if len(words) < 2:
        return None
    ptype, name = words[0], words[1]
    if name in {"READ", "MEMBER", "WRITE", "NOTIFY", "CONSTANT"}:
        return None
    return ptype, name, f"{ptype} {name}"


def parse_type(path: Path, name: str, want_kind: str) -> TypeInfo | None:
    """Extract QML-reachable members of one class/struct body.

    want_kind selects the declaration style: "class" for QObject-derived classes
    (methods and signals) and "gadget" for Q_GADGET structs (properties only).
    """
    lines = read_lines(path)
    start = _find_type_start(lines, name)
    if start is None:
        return None

    end = block_range(lines, start)
    info = TypeInfo(name=name, path=path, line=start + 1)
    info.doc = _doc_above(lines, start)

    visibility = "public"        # public | private | protected
    kind_section = ""            # "" | slots | signals
    guard_stack: list[tuple[str, str]] = []   # (condition, polarity marker)
    buf: list[str] = []
    buf_line = 0
    paren = brace = 0
    doc_buf: list[str] = []

    for i in range(start + 1, end + 1):
        raw = lines[i]
        line = _strip_line_comment(raw)

        gm = IFDEF_RE.match(raw)
        if gm and not buf:
            kind, rest = gm.group(1), gm.group(2).strip()
            if kind in ("if", "ifdef", "ifndef"):
                guard_stack.append((normalize_guard(kind, rest), "+"))
            elif kind == "else" and guard_stack:
                cond, _ = guard_stack.pop()
                guard_stack.append((cond, "!"))
            elif kind == "elif" and guard_stack:
                guard_stack.pop()
                guard_stack.append((f"elif {rest}", "+"))
            elif kind == "endif" and guard_stack:
                guard_stack.pop()
            continue

        sm = SECTION_RE.match(raw)
        if sm and not buf:
            visibility = sm.group(1) or "public"
            kind_section = sm.group(2)
            continue
        vm = VISIBILITY_RE.match(raw)
        if vm and not buf:
            visibility = vm.group(1)
            kind_section = ""
            continue

        stripped = raw.strip()
        if not buf:
            if not stripped:
                doc_buf = []
                continue
            if stripped.startswith("//"):
                doc_buf.append(stripped.lstrip("/").strip())
                continue
            if stripped.startswith("/*") or stripped.startswith("*"):
                doc_buf.append(stripped.strip("/* \t"))
                continue
            if re.fullmatch(r"[A-Z][A-Z0-9_]*", stripped):
                # Q_OBJECT / Q_GADGET / HEADER: a macro that terminates itself.
                doc_buf = []
                continue
            buf_line = i + 1
            doc_text = " ".join(d for d in doc_buf if d)
            doc_buf = []

        buf.append(line)
        paren += line.count("(") - line.count(")")
        brace += line.count("{") - line.count("}")
        text = " ".join(buf)
        finished = False
        if brace == 0 and paren == 0:
            tail = text.strip()
            if tail.endswith(";") or tail.endswith("}"):
                finished = True
            elif tail.startswith("Q_PROPERTY") and tail.endswith(")"):
                finished = True
        elif brace < 0:
            finished = True
        if not finished:
            continue

        stmt = _clean_signature(text)
        buf, paren, brace = [], 0, 0
        if not stmt:
            continue

        guard = " & ".join(("" if pol == "+" else "not ") + cond for cond, pol in guard_stack)
        if visibility != "public":
            continue

        if want_kind == "gadget":
            prop = _parse_property(stmt)
            if prop:
                ptype, pname, decl = prop
                e = Entry(signature=f"{pname}", line=buf_line, kind="property",
                          guard=guard, doc=doc_text, ptype=ptype)
                info.entries.append(e)
                continue
            meth = _parse_method(stmt) if "Q_INVOKABLE" in stmt else None
            if meth:
                ret, sig = meth
                info.entries.append(Entry(signature=sig, line=buf_line, kind="method",
                                          guard=guard, doc=doc_text, ret=ret))
            continue

        if stmt.startswith("Q_PROPERTY"):
            prop = _parse_property(stmt)
            if prop:
                ptype, pname, _ = prop
                info.entries.append(Entry(signature=pname, line=buf_line, kind="property",
                                          guard=guard, doc=doc_text, ptype=ptype))
            continue

        if kind_section == "signals":
            m = re.match(r"^void\s+([A-Za-z_]\w*)\s*\((.*)\);?$", stmt, re.S)
            if m:
                info.entries.append(Entry(signature=f"{m.group(1)}({_format_args(m.group(2))})",
                                          line=buf_line, kind="signal", guard=guard, doc=doc_text))
            continue

        if "Q_INVOKABLE" in stmt or kind_section == "slots":
            meth = _parse_method(stmt)
            if meth:
                ret, sig = meth
                info.entries.append(Entry(signature=sig, line=buf_line, kind="method",
                                          guard=guard, doc=doc_text, ret=ret))

    return info


def _find_type_start(lines: list[str], name: str) -> int | None:
    """Locate the opening brace line of `class|struct name {` (brace may be on the next line)."""
    decl_re = re.compile(r"^\s*(class|struct)\s+" + re.escape(name) + r"\b")
    for i, line in enumerate(lines):
        if not decl_re.match(line):
            continue
        for j in range(i, min(i + 4, len(lines))):
            code = _strip_line_comment(lines[j])
            if ";" in code.split("{", 1)[0]:
                break
            if "{" in code:
                return j
    return None


def normalize_guard(kind: str, cond: str) -> str:
    """Reduce a preprocessor condition to the identifier the reader needs to see."""
    cond = cond.strip()
    if kind in ("ifdef", "ifndef"):
        return cond
    return re.sub(r"^defined\(\s*([A-Za-z_]\w*)\s*\)$", r"\1", cond)


def _doc_above(lines: list[str], idx: int) -> str:
    out: list[str] = []
    i = idx - 1
    while i >= 0:
        s = lines[i].strip()
        if not s:
            if out:
                break
            i -= 1
            continue
        if s.startswith("//"):
            out.append(s.lstrip("/").strip())
        elif s.startswith("*"):
            out.append(s.strip("/* \t"))
        else:
            break
        i -= 1
    return " ".join(reversed([o for o in out if o]))


